package com.alzz26.payments_ledger_service.ledger;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.time.Instant;

/**
 * Entity mapped to the "ledger_transactions" table.
 * Groups the ledger entries created by one operation (e.g. one deposit).
 */
@Entity
@Table(name = "ledger_transactions")
public class LedgerTransaction {

    // Primary key, generated by the database on insert
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Kind of transaction, stored as text (e.g. "DEPOSIT")
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private TransactionType type;

    // Creation time in UTC; excluded from UPDATE statements
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    // No-arg constructor used by JPA when loading rows
    protected LedgerTransaction() {
    }

    // Creates a new transaction and sets createdAt to the current time
    public LedgerTransaction(TransactionType type) {
        this.type = type;
        this.createdAt = Instant.now();
    }

    public Long getId() { return this.id; }
    public TransactionType getType() { return this.type; }
    public Instant getCreatedAt() { return this.createdAt; }
}
