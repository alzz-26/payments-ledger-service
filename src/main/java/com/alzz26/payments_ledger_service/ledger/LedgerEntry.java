package com.alzz26.payments_ledger_service.ledger;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;

/**
 * Entity mapped to the "ledger_entries" table.
 * One row = one amount moved into (+) or out of (-) one account, as part of one transaction.
 */
@Entity
@Table(name = "ledger_entries")
public class LedgerEntry {

    // Primary key, generated by the database on insert
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // The transaction this entry belongs to (column transaction_id), loaded lazily
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "transaction_id", nullable = false)
    private LedgerTransaction transaction;

    // The account this entry moves money in or out of (column account_id), loaded lazily
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "account_id", nullable = false)
    private Account account;

    // Signed amount in minor units (paise): positive = in, negative = out
    @Column(nullable = false)
    private long amount;

    // Creation time in UTC; excluded from UPDATE statements
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    // No-arg constructor used by JPA when loading rows
    protected LedgerEntry() {
    }

    // Creates a new entry and sets createdAt to the current time
    public LedgerEntry(LedgerTransaction transaction, Account account, long amount) {
        this.transaction = transaction;
        this.account = account;
        this.amount = amount;
        this.createdAt = Instant.now();
    }

    public Long getId() { return this.id; }
    public LedgerTransaction getTransaction() { return this.transaction; }
    public Account getAccount() { return this.account; }
    public long getAmount() { return this.amount; }
    public Instant getCreatedAt() { return this.createdAt; }
}
